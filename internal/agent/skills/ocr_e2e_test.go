package skills

import (
	"os"
	"path/filepath"
	"testing"
)

func TestRecognizeTextNoPaddle(t *testing.T) {
	// 造一张最小 PNG 作为输入。
	ws := t.TempDir()
	img := filepath.Join(ws, "in.png")
	// 1x1 透明 PNG
	png := []byte{0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0xf8, 0xcf, 0xc0, 0xf0, 0x1f, 0x00, 0x05, 0x00, 0x01, 0xff, 0x9a, 0x18, 0x1b, 0x02, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82}
	if err := os.WriteFile(img, png, 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := RecognizeText("python3", "ch", img, ws)
	t.Logf("RecognizeText err = %v", err)
	if err == nil {
		t.Log("PaddleOCR 已安装且识别到了文字（或环境已具备）")
	}
}
